WITH ORDERING AS (
    SELECT
        ASOFDATE,
        ROW_NUMBER() OVER (ORDER BY ASOFDATE DESC) AS ROW
    FROM MIDOFFICEREPORTING.ZAINET.ENGIE_DATES
)

SELECT
    A.AS_OF_DATE,
    A.TRADETYPE AS TRADE_TYPE,
    A.BOOK,
    A.TRADE_BS,
    A.DMO,
    A.COMP AS YEAR,
    A.ZKEY,
    CASE A.BOOK_ACCTSUB4
        WHEN 'WAREHOUSING' THEN 'WAREHOUSING'
        WHEN 'TRADING' THEN 'DIRECTIONAL'
        ELSE A.BOOK_ACCTSUB4
    END AS ACTIVITY_TYPE,
    RTRIM(A.TNUM_XREF) AS TNUM_XREF,
    RTRIM(A.[POW SEGMENT2]) AS PROFILE,
    RTRIM(A.MRKTC_ATTR1) AS COMMODITY,
    RTRIM(A.MKT) AS MARKET,
    RTRIM(A.CPTY) AS CPTY,
    CASE
        WHEN
            A.AS_OF_DATE
            = MidOfficeReporting.Zainet.LAST_BUSINESS_DAY(GETDATE())
            THEN 'YES'
        ELSE 'NO'
    END AS LATEST,
    AVG(A.MKTPRC) AS MKT_PRICE,
    SUM(A.DELTA) AS DELTA,
    SUM(A.DELTA_ND) AS DELTA_ND
FROM MIDOFFICEREPORTING.ZAINET.ENGIE_POSITION AS A WITH (NOLOCK)
WHERE
    A.AS_OF_DATE IN (
        SELECT ASOFDATE
        FROM ORDERING
        WHERE ROW IN (1)
    )
    AND A.TRADE_WHATIF <> 'Y'
    AND A.ACTIVE = 1
    AND A.BOOK IN (
        'HMMK', 'HPBW', 'RRHY', 'HPHM', 'HREC', 'REWL', 'TREC', 'GREC', 'HPDS',
        'HPLO', 'HPPD', 'HPPS', 'TPPS', 'HPTN', 'HPIS', 'RPWR', 'ROWN', 'TMAC',
        'HNAT', 'HNEP', 'HNYK', 'HPJR', 'HPLK', 'HSPL', 'HAVW', 'HPSV', 'RHDG',
        'HPSB', 'HPLU'
    )
    AND A.CPTY NOT IN (
        'IHHM', 'ITRC', 'IHRC', 'IHPS', 'IHNP', 'IHNT', 'IHNY', 'IHPJ'
    )
    AND A.CPTY NOT LIKE 'TEMIT%'
    AND A.MRKTC_ATTR1 = 'REC'
GROUP BY
    A.AS_OF_DATE,
    A.TRADETYPE,
    CASE A.BOOK_ACCTSUB4
        WHEN 'WAREHOUSING' THEN 'WAREHOUSING'
        WHEN 'TRADING' THEN 'DIRECTIONAL'
        ELSE A.BOOK_ACCTSUB4
    END,
    A.BOOK,
    A.TRADE_BS,
    RTRIM(A.TNUM_XREF),
    RTRIM(A.[POW SEGMENT2]),
    RTRIM(A.MRKTC_ATTR1),
    A.DMO,
    A.COMP,
    RTRIM(A.MKT),
    A.ZKEY,
    RTRIM(A.CPTY),
    CASE
        WHEN
            A.AS_OF_DATE
            = MidOfficeReporting.Zainet.LAST_BUSINESS_DAY(GETDATE())
            THEN 'YES'
        ELSE 'NO'
    END;
