SELECT
    C0_REPORT_DAT REPORT_DATE,
    C24_TRADE_DATE TRADE_DATE,
    C72_TRADER_EXECUTING TRADER,
    C19_TNUM_XREF TNUM_XREF,
    C5_BOOK BOOK,
    C23_BUY_SELL B_S,
    C26_CPTY CPTY,
    C53_CPTY_DESCR CPTY_DESC,
    SUM(C55__AMT) AMOUNT,
    AVG(C37_PRICE_TRD) TRADE_PRICE
FROM
    tracrisk.Z_BilateralREC
    
GROUP BY 
        C0_REPORT_DAT ,
        C24_TRADE_DATE ,
        C72_TRADER_EXECUTING,
        C19_TNUM_XREF ,
        C5_BOOK ,
        C6_TRADE_TYPE2 ,
        C23_BUY_SELL ,
        C26_CPTY ,
        C53_CPTY_DESCR ,
        C32__CDY_ATTR1 
ORDER BY C26_CPTY
