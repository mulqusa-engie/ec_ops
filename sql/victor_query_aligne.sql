SELECT 
    RTRIM(CPTY) AS cpty,
    COUNT(*) AS legs,
    SUM(DELTA_ND) AS sum_delta_nd
FROM [Zainet].[Engie_Position_Archive]
WHERE AS_OF_DATE = '2026-05-05'
  AND ACTIVE = 1
  AND TRADE_WHATIF = 'N'
  AND RTRIM(BOOK) = 'TREC'
  AND RTRIM(MRKTC_ATTR1) = 'REC'
  AND TRY_CAST(RTRIM(COMP) AS INT) = 2026
GROUP BY RTRIM(CPTY)
ORDER BY ABS(SUM(DELTA_ND)) DESC;